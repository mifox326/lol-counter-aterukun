const DEFAULT_LANE_TIP = (n: string) => `序盤の交易を積み重ねて${n}にプレッシャーを与えレーン主導権を握りやすい。`
const DEFAULT_ACTION_TIP = (n: string) => `${n}の行動を見極めてから得意なスキルで有利に立ち回りやすい。`

function resolveTip(
  championId: string,
  tags: string[],
  opponentName: string,
  specificMap: Record<string, (opponentName: string) => string>,
  tagFallbackMap: Record<string, (opponentName: string) => string>,
  defaultTip: (opponentName: string) => string,
): string {
  const specific = specificMap[championId]
  if (specific) return specific(opponentName)

  for (const tag of tags) {
    const fallback = tagFallbackMap[tag]
    if (fallback) return fallback(opponentName)
  }

  return defaultTip(opponentName)
}

// レーン主導権の握り方(1行目)と、交戦時のスキル活用(2行目)の最大2行を返す。
export function getCounterReasonLines(championId: string, tags: string[], opponentName: string): string[] {
  const laneTip = resolveTip(championId, tags, opponentName, CHAMPION_LANE_TIPS, TAG_FALLBACK_LANE_TIPS, DEFAULT_LANE_TIP)
  const actionTip = resolveTip(championId, tags, opponentName, CHAMPION_ACTION_TIPS, TAG_FALLBACK_ACTION_TIPS, DEFAULT_ACTION_TIP)

  return laneTip === actionTip ? [laneTip] : [laneTip, actionTip]
}
